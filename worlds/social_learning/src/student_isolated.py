from unaiverse.agent import action
from .student import WAgent as StudentAgent
from unaiverse.interaction import Interaction


# The isolated student never participates in the social (best-student) step, so it uses the plain built-in 'process'
# action (grandfather call) instead of the student's relay-augmented one.
class WAgent(StudentAgent):

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)

    def accept_new_role(self, role: int):
        super(StudentAgent, self).accept_new_role(role)  # Use the grandfather method (no best_student_stream to add)

    @action
    async def process(self, interaction: Interaction | None = None) -> bool:
        return await super(StudentAgent, self).process(interaction)  # Plain inference (grandfather method)
